// Regenerates src/lib/chain/abis.ts from the Foundry build output, so the web app is typed
// straight from the contracts and cannot drift from them.
//
//   (cd ../contracts && forge build) && bun run abis
//
// Only functions and errors are exported: the app calls functions, and decodes errors to show a
// plain-language message. Events are the indexer's job.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");

const CONTRACTS = {
  usdAbi: "MockUSD",
  characterAbi: "Character",
  vaultAbi: "SplitVault",
  questAbi: "QuestEscrow",
  battleAbi: "PredictionBattle",
  juryAbi: "Jury",
  treasuryAbi: "CommunityTreasury",
  registryAbi: "CreatorRegistry",
};

/** internalType only names Solidity structs; viem does not need it, and it triples the file size. */
function strip(node) {
  if (Array.isArray(node)) return node.map(strip);
  if (node && typeof node === "object") {
    const next = {};
    for (const [k, v] of Object.entries(node)) if (k !== "internalType") next[k] = strip(v);
    return next;
  }
  return node;
}

let body = `// GENERATED by scripts/export-abis.mjs from contracts/out. Do not edit by hand.\n`;
for (const [exportName, contract] of Object.entries(CONTRACTS)) {
  const artifact = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), "utf8"));
  const items = artifact.abi
    .filter((item) => item.type === "function" || item.type === "error")
    .map(strip)
    .sort((a, b) => `${a.type}:${a.name}`.localeCompare(`${b.type}:${b.name}`));
  body += `\nexport const ${exportName} = [\n${items.map((i) => `  ${JSON.stringify(i)},`).join("\n")}\n] as const;\n`;
}

const target = join(here, "../src/lib/chain/abis.ts");
writeFileSync(target, body);
console.log(`wrote ${target} (${body.split("\n").length} lines)`);
